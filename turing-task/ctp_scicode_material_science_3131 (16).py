import numpy as np
from scipy.optimize import least_squares

def build_dephasing_spectral_density(omega_k, coupling_prefactor, rho_e_lambda,
                                      rho_h_lambda, rho_e_ref, rho_h_ref,
                                      Dc, Dv, omega_grid, omega_tol=0.0):
    if Dc is None or Dv is None or omega_tol is None or not np.isfinite(Dc) or not np.isfinite(Dv):
        raise ValueError("Dc and Dv must be finite")
    if not np.isfinite(omega_tol) or omega_tol < 0.0:
        raise ValueError("omega_tol must be a finite, non-negative tolerance")
    omega_k = np.asarray(omega_k, dtype=np.float64)
    coupling_prefactor = np.asarray(coupling_prefactor, dtype=np.float64)
    rho_e_lambda = np.asarray(rho_e_lambda, dtype=np.complex128)
    rho_h_lambda = np.asarray(rho_h_lambda, dtype=np.complex128)
    rho_e_ref = np.asarray(rho_e_ref, dtype=np.complex128)
    rho_h_ref = np.asarray(rho_h_ref, dtype=np.complex128)
    omega_grid = np.asarray(omega_grid, dtype=np.float64)
    arrays = [omega_k, coupling_prefactor, rho_e_lambda, rho_h_lambda, rho_e_ref, rho_h_ref]
    if any(a.ndim != 1 for a in arrays):
        raise ValueError("all mode arrays must be one-dimensional")
    n_modes = omega_k.shape[0]
    if any(a.shape[0] != n_modes for a in arrays) or n_modes < 1:
        raise ValueError("mode arrays must share the same nonzero length")
    if omega_grid.ndim != 1 or omega_grid.shape[0] < 2:
        raise ValueError("omega_grid must be one-dimensional with at least 2 edges")
    if np.any(omega_k <= 0.0):
        raise ValueError("every phonon mode frequency must be strictly positive")
    if np.any(np.diff(omega_grid) <= 0.0):
        raise ValueError("omega_grid must be strictly increasing")
    lo, hi = omega_grid[0], omega_grid[-1]
    below = omega_k < lo
    above = omega_k > hi
    if np.any(omega_k[below] < lo - omega_tol) or np.any(omega_k[above] > hi + omega_tol):
        raise ValueError("a mode lies outside the tolerance band")
    g_lambda = coupling_prefactor * (Dc * rho_e_lambda - Dv * rho_h_lambda)
    g_ref = coupling_prefactor * (Dc * rho_e_ref - Dv * rho_h_ref)
    w = np.abs(g_lambda - g_ref) ** 2
    weight_folded_low = float(w[below].sum())
    weight_folded_high = float(w[above].sum())
    n_folded_low = int(np.count_nonzero(below))
    n_folded_high = int(np.count_nonzero(above))
    omega_binned = np.where(below, lo, np.where(above, hi, omega_k))
    n_bins = omega_grid.shape[0] - 1
    idx = np.searchsorted(omega_grid, omega_binned, side='right') - 1
    idx = np.clip(idx, 0, n_bins - 1)
    J = np.zeros(n_bins, dtype=np.float64)
    np.add.at(J, idx, w)
    J = J / np.diff(omega_grid)
    return J, weight_folded_low, weight_folded_high, n_folded_low, n_folded_high


def fit_analytical_spectral_density(omega_grid, J_target, Dc, Dv, c_s,
                                     spectral_amplitude, epsilon_reg,
                                     a_e0, a_h0, a_bounds):
    def _analytical_Ja(omega, a_e, a_h, Dc, Dv, c_s, spectral_amplitude):
        omega = np.asarray(omega, dtype=np.float64)
        u_e = Dc * np.exp(-(omega ** 2) * (a_e ** 2) / (4.0 * c_s ** 2))
        u_h = Dv * np.exp(-(omega ** 2) * (a_h ** 2) / (4.0 * c_s ** 2))
        return spectral_amplitude * (omega ** 3) * (u_e - u_h) ** 2
    omega_grid = np.asarray(omega_grid, dtype=np.float64)
    J_target = np.asarray(J_target, dtype=np.float64)
    if omega_grid.ndim != 1 or J_target.ndim != 1:
        raise ValueError("omega_grid and J_target must be one-dimensional")
    if omega_grid.shape[0] != J_target.shape[0] or omega_grid.shape[0] < 3:
        raise ValueError("omega_grid and J_target must share the same length, at least 3")
    if np.any(omega_grid <= 0.0):
        raise ValueError("omega_grid entries must be strictly positive")
    if np.any(J_target < 0.0):
        raise ValueError("J_target must be non-negative everywhere")
    if Dc is None or Dv is None or not np.isfinite(Dc) or not np.isfinite(Dv):
        raise ValueError("Dc and Dv must be finite")
    if c_s is None or not np.isfinite(c_s) or not (c_s > 0.0):
        raise ValueError("c_s must be strictly positive")
    if spectral_amplitude is None or not np.isfinite(spectral_amplitude) or not (spectral_amplitude > 0.0):
        raise ValueError("spectral_amplitude must be strictly positive")
    if epsilon_reg is None or not np.isfinite(epsilon_reg) or not (epsilon_reg > 0.0):
        raise ValueError("epsilon_reg must be strictly positive")
    if a_bounds is None:
        raise ValueError("a_bounds must be provided")
    lo, hi = a_bounds
    if lo is None or hi is None or not np.isfinite(lo) or not np.isfinite(hi) or not (0.0 < lo < hi):
        raise ValueError("a_bounds must satisfy 0 < lo < hi")
    if (a_e0 is None or a_h0 is None or not np.isfinite(a_e0) or not np.isfinite(a_h0)
            or not (lo <= a_e0 <= hi and lo <= a_h0 <= hi)):
        raise ValueError("initial guesses must lie within a_bounds")
    weight = np.sqrt(J_target + epsilon_reg)
    def residual(params):
        a_e, a_h = params
        Ja = _analytical_Ja(omega_grid, a_e, a_h, Dc, Dv, c_s, spectral_amplitude)
        return (Ja - J_target) / weight
    result = least_squares(residual, x0=[a_e0, a_h0], bounds=([lo, lo], [hi, hi]), method='trf')
    n_points = omega_grid.shape[0]
    dof = n_points - 2
    J_w = result.jac
    try:
        cov_shape = np.linalg.inv(J_w.T @ J_w)
    except np.linalg.LinAlgError:
        raise ValueError("the fit is not well-constrained enough to determine a parameter covariance")
    d0, d1 = cov_shape[0, 0], cov_shape[1, 1]
    if not (d0 > 0.0 and d1 > 0.0):
        raise ValueError("the fit is not well-constrained enough to determine a parameter covariance")
    rho_ae_ah = float(cov_shape[0, 1] / np.sqrt(d0 * d1))
    chi2_red = 2.0 * result.cost / dof
    variances = np.diag(cov_shape) * chi2_red
    if np.any(variances < 0.0):
        raise ValueError("the fit is not well-constrained enough to determine a parameter covariance")
    sigma = np.sqrt(variances)
    weighted_rmse = float(np.sqrt(2.0 * result.cost / n_points))
    return {
        'a_e': float(result.x[0]),
        'a_h': float(result.x[1]),
        'cost': float(result.cost),
        'sigma_a_e': float(sigma[0]),
        'sigma_a_h': float(sigma[1]),
        'chi2_red': float(chi2_red),
        'rho_ae_ah': rho_ae_ah,
        'weighted_rmse': weighted_rmse,
    }


def analyze_phonon_assisted_bandwidth(omega_k, coupling_prefactor, rho_e_lambda,
                                       rho_h_lambda, rho_e_ref, rho_h_ref,
                                       Dc, Dv, omega_grid, c_s, spectral_amplitude,
                                       epsilon_reg, a_e0, a_h0, a_bounds,
                                       threshold_fraction):
    def _analytical_Ja(omega, a_e, a_h, Dc, Dv, c_s, spectral_amplitude):
        omega = np.asarray(omega, dtype=np.float64)
        u_e = Dc * np.exp(-(omega ** 2) * (a_e ** 2) / (4.0 * c_s ** 2))
        u_h = Dv * np.exp(-(omega ** 2) * (a_h ** 2) / (4.0 * c_s ** 2))
        return spectral_amplitude * (omega ** 3) * (u_e - u_h) ** 2
    if not (0.0 < threshold_fraction < 1.0):
        raise ValueError("threshold_fraction must lie strictly between 0 and 1")
    J_numeric, _, _, _, _ = build_dephasing_spectral_density(
        omega_k, coupling_prefactor, rho_e_lambda, rho_h_lambda,
        rho_e_ref, rho_h_ref, Dc, Dv, omega_grid)
    omega_centers = 0.5 * (omega_grid[:-1] + omega_grid[1:])
    fit = fit_analytical_spectral_density(
        omega_centers, J_numeric, Dc, Dv, c_s, spectral_amplitude,
        epsilon_reg, a_e0, a_h0, a_bounds)
    J_analytical = _analytical_Ja(omega_centers, fit['a_e'], fit['a_h'],
                                   Dc, Dv, c_s, spectral_amplitude)
    def bandwidth(omega_c, J_curve, label):
        J_peak = float(np.max(J_curve))
        if not (J_peak > 0.0):
            raise ValueError(f"{label} spectral density is identically zero or non-positive")
        i_peak = int(np.flatnonzero(J_curve == J_peak)[0])
        if i_peak >= len(J_curve) - 1:
            raise ValueError(f"{label} spectral density has no resolved decaying branch")
        omega_peak = omega_c[i_peak]
        level = threshold_fraction * J_peak
        crossing = None
        for i in range(i_peak + 1, len(J_curve)):
            if J_curve[i] <= level:
                crossing = i
                break
        if crossing is None:
            raise ValueError(f"omega_grid does not extend far enough for {label}")
        i0, i1 = crossing - 1, crossing
        w0, w1 = omega_c[i0], omega_c[i1]
        J0, J1 = J_curve[i0], J_curve[i1]
        omega_star = w0 + (level - J0) * (w1 - w0) / (J1 - J0)
        return omega_peak, float(omega_star - omega_peak)
    omega_peak_atomistic, bw_atomistic = bandwidth(omega_centers, J_numeric, "atomistic")
    _, bw_analytical = bandwidth(omega_centers, J_analytical, "analytical")
    enhancement_factor = bw_atomistic / bw_analytical
    return {
        'a_e_fit': fit['a_e'],
        'a_h_fit': fit['a_h'],
        'omega_peak_atomistic': float(omega_peak_atomistic),
        'bandwidth_atomistic': float(bw_atomistic),
        'bandwidth_analytical': float(bw_analytical),
        'enhancement_factor': float(enhancement_factor),
    }