import numpy as np

def build_dephasing_spectral_density(omega_k, coupling_prefactor, rho_e_lambda,
                                      rho_h_lambda, rho_e_ref, rho_h_ref,
                                      Dc, Dv, omega_grid, omega_tol=0.0):
    '''Inputs:
        omega_k : numpy.ndarray, shape (n_modes,), dtype float64
        coupling_prefactor : numpy.ndarray, shape (n_modes,), dtype float64
        rho_e_lambda, rho_h_lambda : numpy.ndarray, shape (n_modes,), dtype complex128
        rho_e_ref, rho_h_ref : numpy.ndarray, shape (n_modes,), dtype complex128
        Dc, Dv : float
        omega_grid : numpy.ndarray, shape (n_bins+1,), dtype float64
        omega_tol : float, optional. Defaults to 0.0.

    Outputs:
        J : numpy.ndarray, shape (n_bins,), dtype float64
        weight_folded_low : float
        weight_folded_high : float
        n_folded_low : int
        n_folded_high : int

    Raises:
        ValueError: on invalid inputs or out-of-range modes.'''
    omega_k = np.asarray(omega_k, dtype=np.float64)
    coupling_prefactor = np.asarray(coupling_prefactor, dtype=np.float64)
    rho_e_lambda = np.asarray(rho_e_lambda, dtype=np.complex128)
    rho_h_lambda = np.asarray(rho_h_lambda, dtype=np.complex128)
    rho_e_ref = np.asarray(rho_e_ref, dtype=np.complex128)
    rho_h_ref = np.asarray(rho_h_ref, dtype=np.complex128)
    omega_grid = np.asarray(omega_grid, dtype=np.float64)
    arrays = [omega_k, coupling_prefactor, rho_e_lambda, rho_h_lambda, rho_e_ref, rho_h_ref]
    if any(a.ndim != 1 for a in arrays):
        raise ValueError("all mode arrays must be one-dimensional")
    n_modes = omega_k.shape[0]
    if any(a.shape[0] != n_modes for a in arrays) or n_modes < 1:
        raise ValueError("mode arrays must share the same nonzero length")
    if omega_grid.ndim != 1 or omega_grid.shape[0] < 2:
        raise ValueError("omega_grid must be one-dimensional with at least 2 edges")
    if Dc is None or Dv is None or not np.isfinite(Dc) or not np.isfinite(Dv):
        raise ValueError("Dc and Dv must be finite")
    if np.any(omega_k <= 0.0):
        raise ValueError("every phonon mode frequency must be strictly positive")
    if np.any(np.diff(omega_grid) <= 0.0):
        raise ValueError("omega_grid must be strictly increasing")
    if omega_tol is None or not np.isfinite(omega_tol) or omega_tol < 0.0:
        raise ValueError("omega_tol must be a finite, non-negative tolerance")
    lo, hi = omega_grid[0], omega_grid[-1]
    below = omega_k < lo
    above = omega_k > hi
    if np.any(omega_k[below] < lo - omega_tol) or np.any(omega_k[above] > hi + omega_tol):
        raise ValueError("a mode lies outside the tolerance band")
    g_lambda = coupling_prefactor * (Dc * rho_e_lambda - Dv * rho_h_lambda)
    g_ref = coupling_prefactor * (Dc * rho_e_ref - Dv * rho_h_ref)
    weight = np.abs(g_lambda - g_ref) ** 2
    weight_folded_low = float(weight[below].sum())
    weight_folded_high = float(weight[above].sum())
    n_folded_low = int(np.count_nonzero(below))
    n_folded_high = int(np.count_nonzero(above))
    omega_binned = np.where(below, lo, np.where(above, hi, omega_k))
    n_bins = omega_grid.shape[0] - 1
    idx = np.searchsorted(omega_grid, omega_binned, side='right') - 1
    idx = np.clip(idx, 0, n_bins - 1)
    J = np.zeros(n_bins, dtype=np.float64)
    np.add.at(J, idx, weight)
    J = J / np.diff(omega_grid)
    return J, weight_folded_low, weight_folded_high, n_folded_low, n_folded_high

