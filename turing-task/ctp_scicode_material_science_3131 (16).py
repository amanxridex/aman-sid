import numpy as np
from scipy.optimize import least_squares

def fit_analytical_spectral_density(omega_grid, J_target, Dc, Dv, c_s,
                                     spectral_amplitude, epsilon_reg,
                                     a_e0, a_h0, a_bounds):
    '''Inputs:
        omega_grid : numpy.ndarray, shape (n,), dtype float64
        J_target : numpy.ndarray, shape (n,), dtype float64
        Dc, Dv : float
        c_s : float
        spectral_amplitude : float
        epsilon_reg : float
        a_e0, a_h0 : float
        a_bounds : tuple of float

    Outputs:
        result : dict with 7 keys.

    Raises:
        ValueError: on invalid inputs or non-identifiable parameters.'''
    def _Ja(omega, a_e, a_h):
        omega = np.asarray(omega, dtype=np.float64)
        u_e = Dc * np.exp(-(omega ** 2) * (a_e ** 2) / (4.0 * c_s ** 2))
        u_h = Dv * np.exp(-(omega ** 2) * (a_h ** 2) / (4.0 * c_s ** 2))
        return spectral_amplitude * (omega ** 3) * (u_e - u_h) ** 2
    omega_grid = np.asarray(omega_grid, dtype=np.float64)
    J_target = np.asarray(J_target, dtype=np.float64)
    if omega_grid.ndim != 1 or J_target.ndim != 1:
        raise ValueError("omega_grid and J_target must be one-dimensional")
    if omega_grid.shape[0] != J_target.shape[0] or omega_grid.shape[0] < 3:
        raise ValueError("omega_grid and J_target must share the same length, at least 3")
    if np.any(omega_grid <= 0.0):
        raise ValueError("omega_grid entries must be strictly positive")
    if np.any(J_target < 0.0):
        raise ValueError("J_target must be non-negative everywhere")
    if Dc is None or Dv is None or not np.isfinite(Dc) or not np.isfinite(Dv):
        raise ValueError("Dc and Dv must be finite")
    if c_s is None or not np.isfinite(c_s) or not (c_s > 0.0):
        raise ValueError("c_s must be strictly positive")
    if spectral_amplitude is None or not np.isfinite(spectral_amplitude) or not (spectral_amplitude > 0.0):
        raise ValueError("spectral_amplitude must be strictly positive")
    if epsilon_reg is None or not np.isfinite(epsilon_reg) or not (epsilon_reg > 0.0):
        raise ValueError("epsilon_reg must be strictly positive")
    if a_bounds is None:
        raise ValueError("a_bounds must be provided")
    lo, hi = a_bounds
    if lo is None or hi is None or not np.isfinite(lo) or not np.isfinite(hi) or not (0.0 < lo < hi):
        raise ValueError("a_bounds must satisfy 0 < lo < hi")
    if (a_e0 is None or a_h0 is None or not np.isfinite(a_e0) or not np.isfinite(a_h0)
            or not (lo <= a_e0 <= hi and lo <= a_h0 <= hi)):
        raise ValueError("initial guesses must lie within a_bounds")
    weight = np.sqrt(J_target + epsilon_reg)
    def residual(params):
        a_e, a_h = params
        return (_Ja(omega_grid, a_e, a_h) - J_target) / weight
    result = least_squares(residual, x0=[a_e0, a_h0],
                            bounds=([lo, lo], [hi, hi]), method='trf')
    n_points = omega_grid.shape[0]
    dof = n_points - 2
    J_w = result.jac
    try:
        cov_shape = np.linalg.inv(J_w.T @ J_w)
    except np.linalg.LinAlgError:
        raise ValueError("the fit is not well-constrained enough to determine a parameter covariance")
    d0, d1 = cov_shape[0, 0], cov_shape[1, 1]
    if not (d0 > 0.0 and d1 > 0.0):
        raise ValueError("the fit is not well-constrained enough to determine a parameter covariance")
    rho_ae_ah = float(cov_shape[0, 1] / np.sqrt(d0 * d1))
    chi2_red = 2.0 * result.cost / dof
    variances = np.diag(cov_shape) * chi2_red
    if np.any(variances < 0.0):
        raise ValueError("the fit is not well-constrained enough to determine a parameter covariance")
    sigma = np.sqrt(variances)
    return {
        'a_e': float(result.x[0]),
        'a_h': float(result.x[1]),
        'cost': float(result.cost),
        'sigma_a_e': float(sigma[0]),
        'sigma_a_h': float(sigma[1]),
        'chi2_red': float(chi2_red),
        'rho_ae_ah': rho_ae_ah,
    }

